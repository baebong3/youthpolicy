_PAT = []
_END = r'(?=$|[^가-힣]|시|군|구|도|읍|면|의|에|은|는|이|가|을|를|서|와|과|로|형|권|산|공항|한옥|항|역|시내)'   # 시군명 뒤 : 행정단위 · 조사만 허용
for sd, names in ALIAS.items():
    for nm in sorted(names.split(), key=len, reverse=True):
        big = nm in SIDO or len(nm) >= 3 or nm in ('서울', '부산', '대구', '인천', '대전', '울산', '제주')
        _PAT.append((re.compile(r'(?<![가-힣])' + nm + ('' if big else _END)), sd))
for sd, names in STRICT.items():
    for nm in names.split():
        _PAT.append((re.compile(r'(?<![가-힣])' + nm + r'(시|군)(?![가-힣]*(청년|민))'), sd))
# '경기(도) 광주'는 경기로, 그 밖의 '광주' · '광주시'는 광주광역시로
_PAT.insert(0, (re.compile(r'경기(도)?\s*광주'), '경기'))


def regions(title):
    t = re.sub(r'\[[^\]]*\]', ' ', title or '')
    found = set()
    for pat, sd in _PAT:
        if pat.search(t):
            if sd == '광주' and re.search(r'경기(도)?\s*광주', t):
                continue
            found.add(sd)
    return found


